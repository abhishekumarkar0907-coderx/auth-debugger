import React, { useEffect, useState } from 'react';
import type { AiExplanationLoader, AiExplanationResponse, AiExplanationUiState } from '../services/aiExplanation.ts';
import { getExplanationFailureState, getExplanationUiState } from '../services/aiExplanation.ts';
import type { SpanRecord } from '../types.ts';
import type { InvestigationDataSource } from '../services/investigationApi.ts';
import { findReferencedSpans } from '../utils/securityEvidence.ts';
import { renderAiExplanationState } from '../utils/aiExplanationView.ts';
import './AiExplanationPanel.css';

interface AiExplanationPanelProps {
  findingId: string | null;
  loadExplanation: AiExplanationLoader;
  dataSource?: InvestigationDataSource;
  evidence?: Record<string, unknown>;
  spans?: SpanRecord[];
  onSelectSpan?: (spanId: string) => void;
}

export const AiExplanationPanel: React.FC<AiExplanationPanelProps> = ({
  findingId,
  loadExplanation,
  dataSource = 'live',
  evidence = {},
  spans = [],
  onSelectSpan,
}) => {
  const [state, setState] = useState<AiExplanationUiState>({ kind: 'idle' });
  const [retry, setRetry] = useState(0);

  useEffect(() => {
    if (!findingId) {
      setState({ kind: 'idle' });
      return;
    }
    const controller = new AbortController();
    let cancelled = false;
    let timedOut = false;
    const timer = window.setTimeout(() => {
      timedOut = true;
      controller.abort();
    }, 25_000);
    setState({ kind: 'loading' });
    loadExplanation(findingId, controller.signal)
      .then((response: AiExplanationResponse) => {
        if (cancelled) return;
        setState(timedOut
          ? getExplanationFailureState(new Error('The explanation request timed out.'), true)
          : getExplanationUiState(response));
      })
      .catch((error: unknown) => {
        if (!cancelled) setState(getExplanationFailureState(error, timedOut));
      })
      .finally(() => window.clearTimeout(timer));
    return () => {
      cancelled = true;
      window.clearTimeout(timer);
      controller.abort();
    };
  }, [findingId, loadExplanation, retry]);

  return (
    <section className="ai-explanation-panel" aria-labelledby="ai-explanation-title" aria-live="polite">
      <header>
        <div><p className="security-eyebrow">EVIDENCE-GROUNDED ASSISTANCE</p><h4 id="ai-explanation-title">{dataSource === 'demo' ? 'Sample explanation' : 'AI explanation'}</h4></div>
        {findingId && <span className="ai-source-verdict">{dataSource === 'demo' ? 'Demo text' : 'Optional model output'}</span>}
      </header>
      {state.kind !== 'ready' && renderAiExplanationState(state, () => setRetry((n) => n + 1))}
      {state.kind === 'ready' && state.response.explanation && (
        <div className="ai-explanation-content">
          {dataSource === 'demo' && <p className="ai-demo-note">Sample wording for the walkthrough. This text was not generated by an AI model and is not a live security explanation.</p>}
          <Claim title="Summary" claim={state.response.explanation.summary} evidence={evidence} spans={spans} onSelectSpan={onSelectSpan} />
          <Claim title="Why the detector flagged it" claim={state.response.explanation.why_detected} evidence={evidence} spans={spans} onSelectSpan={onSelectSpan} />
          <Claim title="Authority difference" claim={state.response.explanation.authority_difference} evidence={evidence} spans={spans} onSelectSpan={onSelectSpan} />
          <Claim title="Request path" claim={state.response.explanation.request_path_explanation} evidence={evidence} spans={spans} onSelectSpan={onSelectSpan} />
          {state.response.explanation.limitations.length > 0 && <div><strong>Limitations</strong><ul>{state.response.explanation.limitations.map((item, i) => <li key={i}>{item}</li>)}</ul></div>}
          {state.response.explanation.remediation.length > 0 && <div><strong>Remediation to consider</strong>{state.response.explanation.remediation.map((claim, i) => <Claim key={i} title="" claim={claim} evidence={evidence} spans={spans} onSelectSpan={onSelectSpan} />)}</div>}
          <p className="ai-authority-note">This text explains the deterministic finding; it does not set or change the verdict or severity.</p>
        </div>
      )}
    </section>
  );
};

const Claim: React.FC<{
  title: string;
  claim: { text: string; evidence_refs: string[] };
  evidence: Record<string, unknown>;
  spans: SpanRecord[];
  onSelectSpan?: (spanId: string) => void;
}> = ({ title, claim, evidence, spans, onSelectSpan }) => (
  <div className="ai-claim">
    {title && <strong>{title}</strong>}
    <p>{claim.text}</p>
    {claim.evidence_refs.length > 0 && (
      <div className="ai-evidence-refs" aria-label="Explanation evidence references">
        {claim.evidence_refs.map((reference) => {
          const supportingSpans = findReferencedSpans(reference, evidence, spans);
          return supportingSpans.length > 0 ? supportingSpans.map((span) => (
            <button key={`${reference}-${span.span_id}`} type="button" onClick={() => onSelectSpan?.(span.span_id)}>
              {reference} · Open {span.service_name || span.span_name}
            </button>
          )) : <span key={reference}>{reference}</span>;
        })}
      </div>
    )}
  </div>
);
